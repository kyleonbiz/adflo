import { toCsv } from "@/lib/csv";
import { shellQuote } from "./paths";
import type { Change } from "./types";

export function planToCsv(changes: Change[]): string {
  return toCsv([["From", "To", "Why"], ...changes.map((c) => [c.from, c.to, c.reasons.map((r) => r.detail).join("; ")])]);
}

const HEADER = (title: string, note: string) =>
  [
    "#!/bin/sh",
    `# ${title}`,
    `# ${note}`,
    "# It only moves and renames. It never deletes, and it never overwrites an existing file.",
    "# Usage: sh script.sh /path/to/the/folder",
    "set -u",
    'ROOT=${1:?"Usage: sh script.sh /path/to/the/folder"}',
    'cd "$ROOT" || exit 1',
    "move() {",
    '  if [ ! -e "$1" ]; then echo "Skipped (not found): $1"; return; fi',
    '  if [ -e "$2" ]; then echo "Skipped (already exists): $2"; return; fi',
    '  mkdir -p -- "$(dirname -- "$2")" && mv -n -- "$1" "$2" && echo "Moved: $1 -> $2"',
    "}",
    "",
  ].join("\n");

// "./" keeps a name that starts with "-" from ever looking like an option.
const line = (from: string, to: string) => `move ${shellQuote(`./${from}`)} ${shellQuote(`./${to}`)}`;

export function moveScript(changes: Change[]): string {
  return HEADER("Folder cleanup", "Generated by Aurum Ventura Business File Reset.") + changes.map((c) => line(c.from, c.to)).join("\n") + "\n";
}

/** Reverses a cleanup: every file goes back where it was. Folders created by the cleanup are left in place. */
export function undoScript(changes: Change[]): string {
  return HEADER("Undo folder cleanup", "Puts every file back where it was before the cleanup.") + [...changes].reverse().map((c) => line(c.to, c.from)).join("\n") + "\n";
}
